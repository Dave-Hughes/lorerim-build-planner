def slug(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def svg(grid, size=16):
    rows = [r for r in grid.strip("\n").split("\n")]
    assert len(rows) == size, f"{len(rows)} rows"
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {size} {size}" shape-rendering="crispEdges">']
    for y, row in enumerate(rows):
        assert len(row) == size, f"row {y} has {len(row)} cells: {row!r}"
        x = 0
        while x < size:
            c = row[x]
            if c == ".":
                x += 1
                continue
            run = 1
            while x + run < size and row[x + run] == c:
                run += 1
            out.append(f'<rect x="{x}" y="{y}" width="{run}" height="1" fill="{PALETTE[c]}"/>')
            x += run
    out.append("</svg>")
    return "\n".join(out)


def main():
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    out = os.path.join(root, "public", "icons")
    os.makedirs(out, exist_ok=True)
    for name, grid in ICONS.items():
        with open(os.path.join(out, slug(name) + ".svg"), "w") as f:
            f.write(svg(grid))
    print(len(ICONS), "icons ->", os.path.relpath(out, root))


if __name__ == "__main__":
    main()
